func TestLockIsWrittenAsYAML(t *testing.T) {
	l := Lock{Version: 1, Repositories: map[string]LockedRepository{"app": {Inputs: LockInputs{URL: "https://gitlab.com/g/app", Provider: "gitlab", TokenEnv: "T"}, RepositoryID: "9", SourceRepositoryID: "9", DefaultBranch: "main", BotUserID: "5"}}}
	var b bytes.Buffer
	if e := EncodeLock(&b, l); e != nil {
		t.Fatal(e)
	}
	out := b.String()
	if !strings.HasPrefix(out, "# Generated by reviewd config resolve") || !strings.Contains(out, "repository_id: \"9\"") || strings.Contains(out, "{") {
		t.Fatalf("lock not readable YAML:\n%s", out)
	}
	back, e := DecodeLock(strings.NewReader(out))
	if e != nil || back.Repositories["app"] != l.Repositories["app"] {
		t.Fatalf("round trip %+v %v", back, e)
	}
}
