const yamlConfig = `# changeharbor.yaml
version: 1
models:
  default: models/review.yaml # shared model config
repositories:
  app:
    url: https://gitlab.com/group/app
    token_env: GITLAB_TOKEN
    bot_user_id: 12345        # unquoted IDs stay text
    branch: 1.10              # never becomes 1.1
    mirror:
      path: /mirrors/app.git
      sync: none
    policy: policies/app.json
    publish:
      approvals: off          # YAML 1.2: a string, not false
      comments: post
    gitlab:
      ci_trust: unchanged_config
      ci_paths:
        - .gitlab/ci/**
        - scripts/ci-*.sh
`

func TestYAMLConfigWithComments(t *testing.T) {
	s, src, e := DecodeSettings(strings.NewReader(yamlConfig), "/base")
	if e != nil {
		t.Fatal(e)
	}
	r := s.Repositories["app"]
	if r.BotUserID != "12345" || r.Branch != "1.10" || r.Publish.Approvals != "off" || r.Publish.Comments != "post" ||
		r.Mirror.Sync != "none" || len(r.GitLab.CIPaths) != 2 || r.Model != "default" || s.Models["default"] != "/base/models/review.yaml" {
		t.Fatalf("%+v", r)
	}
	if src["repositories.app.publish.approvals"] != "file" || src["repositories.app.model"] != "default" {
		t.Fatalf("sources %v", src)
	}
}

func TestYAMLRejectsAmbiguousConstructs(t *testing.T) {
	base := strings.Replace(yamlConfig, "    branch: 1.10              # never becomes 1.1\n", "", 1)
	for _, tc := range []struct{ name, doc, want string }{
		{"null value", strings.Replace(base, "token_env: GITLAB_TOKEN", "token_env:", 1), "repositories.app.token_env: null value (line 8); omit the key to use the default"},
		{"bool in text field", strings.Replace(base, "comments: post", "comments: true", 1), `repositories.app.publish.comments: must be text (line 16); quote it if you meant "true"`},
		{"anchor and alias", strings.Replace(base, "policy: policies/app.json", "policy: &p policies/app.json\n    response: *p", 1), "anchors and aliases are not supported"},
		{"custom tag", strings.Replace(base, "policy: policies/app.json", "policy: !!binary cG9saWN5", 1), "unsupported YAML tag !!binary"},
		{"merge key", strings.Replace(base, "    publish:\n", "    <<: {}\n    publish:\n", 1), "merge keys are not supported"},
		{"duplicate key", strings.Replace(base, "version: 1", "version: 1\nversion: 1", 1), "duplicate key"},
		{"second document", base + "---\nversion: 1\n", "exactly one YAML document"},
		{"typo still suggested", strings.Replace(base, "ci_trust:", "ci_trus:", 1), `repositories.app.gitlab.ci_trus: unknown key; did you mean "ci_trust"?`},
		{"list where text expected", strings.Replace(base, "policy: policies/app.json", "policy: [a, b]", 1), "repositories.app.policy: must be text"},
		{"text where number expected", strings.Replace(base, "version: 1", `version: "1"`, 1), "version: must be a number"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, _, e := DecodeSettings(strings.NewReader(tc.doc), "/base")
			if e == nil || !strings.Contains(e.Error(), tc.want) {
				t.Fatalf("error %v, want %q", e, tc.want)
			}
		})
	}
}

